"""YOLO 数据集管理。

支持创建/删除/列出数据集，管理标注图片和标签。
支持从 DOM XML 自动生成 YOLO 格式标签（免手工标注）。

参考 mobile_vision 的 ``app/yolo/controller.py``。
"""
from __future__ import annotations

import os
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any


class DatasetManager:
    """管理 YOLO 训练数据集。"""

    def __init__(self, datasets_dir: str = "./datasets/yolo") -> None:
        self._root = Path(datasets_dir)
        self._root.mkdir(parents=True, exist_ok=True)

    def create_dataset(
        self,
        name: str,
        description: str = "",
        classes: list[str] | None = None,
    ) -> Path:
        """创建一个新数据集目录。

        创建 YOLO 标准目录结构::

            datasets/{name}/
                images/train/
                images/val/
                labels/train/
                labels/val/
                data.yaml

        Args:
            name: 数据集名称（也是目录名）。
            description: 描述信息。
            classes: 类别名称列表。

        Returns:
            数据集根目录的 Path。
        """
        ds_dir = self._root / name
        if ds_dir.exists():
            raise FileExistsError(f"数据集 '{name}' 已存在: {ds_dir}")

        # 创建目录结构
        (ds_dir / "images" / "train").mkdir(parents=True)
        (ds_dir / "images" / "val").mkdir(parents=True)
        (ds_dir / "labels" / "train").mkdir(parents=True)
        (ds_dir / "labels" / "val").mkdir(parents=True)

        # 写入描述文件
        if description:
            (ds_dir / "README.txt").write_text(description, encoding="utf-8")

        # 写入 classes.txt
        if classes:
            (ds_dir / "classes.txt").write_text(
                "\n".join(classes), encoding="utf-8"
            )

        # 生成 data.yaml
        self._generate_data_yaml(ds_dir, classes or [])

        return ds_dir

    def _generate_data_yaml(self, ds_dir: Path, classes: list[str]) -> Path:
        """生成 YOLO data.yaml 配置文件。"""
        yaml_path = ds_dir / "data.yaml"
        nc = len(classes)
        names_str = str(classes).replace("'", '"') if classes else '["object"]'

        yaml_content = f"""# YOLO Dataset Configuration
# Generated by TestAgent DatasetManager

train: {ds_dir}/images/train
val: {ds_dir}/images/val

nc: {nc}
names: {names_str}
"""
        # Use YAML format compatible with ultralytics
        if classes:
            names_dict = "{" + ", ".join(f"{i}: '{c}'" for i, c in enumerate(classes)) + "}"
            yaml_content = f"""# YOLO Dataset Configuration
train: {ds_dir}/images/train
val: {ds_dir}/images/val

nc: {nc}
names: {names_dict}
"""

        yaml_path.write_text(yaml_content, encoding="utf-8")
        return yaml_path

    def delete_dataset(self, name: str) -> None:
        """删除数据集（会递归删除所有文件！）。"""
        import shutil

        ds_dir = self._root / name
        if ds_dir.exists():
            shutil.rmtree(ds_dir)

    def list_datasets(self) -> list[dict[str, Any]]:
        """列出所有可用数据集。"""
        datasets: list[dict[str, Any]] = []
        for item in self._root.iterdir():
            if item.is_dir() and (item / "images").exists():
                image_count = sum(1 for _ in (item / "images" / "train").glob("*.*"))
                val_count = sum(1 for _ in (item / "images" / "val").glob("*.*"))
                label_count = sum(1 for _ in (item / "labels" / "train").glob("*.txt"))
                val_label_count = sum(1 for _ in (item / "labels" / "val").glob("*.txt"))
                classes = []
                if (item / "classes.txt").exists():
                    classes = item.joinpath("classes.txt").read_text(encoding="utf-8").strip().split("\n")
                description = ""
                if (item / "README.txt").exists():
                    description = item.joinpath("README.txt").read_text(encoding="utf-8")

                datasets.append({
                    "name": item.name,
                    "path": str(item),
                    "description": description,
                    "classes": classes,
                    "class_count": len(classes),
                    "image_count": image_count + val_count,
                    "train_images": image_count,
                    "val_images": val_count,
                    "label_count": label_count + val_label_count,
                })
        return datasets

    def add_images(self, dataset_name: str, image_dir: str, split: str = "train") -> int:
        """从目录复制图片到数据集。

        Args:
            dataset_name: 数据集名称。
            image_dir: 图片文件目录。
            split: "train" 或 "val"。

        Returns:
            复制的图片数量。
        """
        ds_dir = self._root / dataset_name
        if not ds_dir.exists():
            raise FileNotFoundError(f"数据集 '{dataset_name}' 不存在")

        target_dir = ds_dir / "images" / split
        target_dir.mkdir(parents=True, exist_ok=True)

        import shutil

        count = 0
        src_dir = Path(image_dir)
        for f in src_dir.glob("*.*"):
            if f.suffix.lower() in (".png", ".jpg", ".jpeg", ".bmp"):
                shutil.copy2(f, target_dir / f.name)
                count += 1
        return count

    def get_dataset_path(self, name: str) -> Path:
        """获取数据集路径。"""
        return self._root / name

    def data_yaml_exists(self, name: str) -> bool:
        """检查 data.yaml 是否存在。"""
        return (self._root / name / "data.yaml").exists()

    def get_data_yaml(self, name: str) -> str | None:
        """获取 data.yaml 内容。"""
        yaml_path = self._root / name / "data.yaml"
        if yaml_path.exists():
            return yaml_path.read_text(encoding="utf-8")
        return None

    # ── 自动标注：DOM XML → YOLO 标签 ──────────────────────────

    @staticmethod
    def auto_label_from_dom(
        dom_xml: str,
        image_width: int,
        image_height: int,
        class_map: dict[str, int] | None = None,
    ) -> tuple[str, list[dict[str, Any]]]:
        """从 DOM XML 自动生成 YOLO 格式标签内容 + 元素元数据。

        核心思路：UiAutomator2 返回的 XML 已经包含了每个元素的
        精确 bounds（像素坐标）和类型信息。我们利用这些数据直接
        生成 YOLO 训练标签，无需人工标注。

        DOM 只能给出结构类型（Button/TextView），无法直接给出
        语义含义（"登录按钮" vs "搜索按钮"）。但是 DOM 的 text/
        content-desc 属性包含了文字内容，保存在返回的 metadata 中。

        在运行时，YOLO+OCR 管线自动叠加文字识别结果，
        LLM 根据文字内容做精确匹配。

        Args:
            dom_xml: uiautomator2 返回的 UI hierarchy XML。
            image_width: 截图宽度（px）。
            image_height: 截图高度（px）。
            class_map: 结构类型名 → 类别ID 的映射。
                如 {"Button": 0, "EditText": 1, "TextView": 2}。
                为 None 时自动推断。

        Returns:
            (yolo_label_text, metadata_list)
            - yolo_label_text: YOLO 格式标签，每行 ``class_id cx cy w h``
            - metadata_list: 每个标注元素的详细信息，包含 text 内容
        """
        lines: list[str] = []
        metadata: list[dict[str, Any]] = []
        used_classes: dict[str, int] = class_map or {}
        next_id = max(used_classes.values()) + 1 if used_classes else 0

        try:
            root = ET.fromstring(dom_xml.encode("utf-8"))
        except Exception:
            return "", []

        # 计算有用类别的分数（用于优化类别命名）
        type_scores: dict[str, int] = {}

        # 递归提取可点击/有文本的元素
        def _extract(node: ET.Element, depth: int = 0) -> None:
            nonlocal next_id
            bounds_str = node.get("bounds", "")
            if not bounds_str:
                for child in node:
                    _extract(child, depth + 1)
                return

            match = re.match(r"\[(\d+),(\d+)\]\[(\d+),(\d+)\]", bounds_str)
            if not match:
                for child in node:
                    _extract(child, depth + 1)
                return

            x1, y1, x2, y2 = int(match[1]), int(match[2]), int(match[3]), int(match[4])
            if x2 - x1 < 5 or y2 - y1 < 5:
                for child in node:
                    _extract(child, depth + 1)
                return

            class_name = node.get("class", "")
            type_short = class_name.split(".")[-1] if class_name else "unknown"
            text = node.get("text", "") or ""
            content_desc = node.get("content-desc", "") or ""
            resource_id = node.get("resource-id", "") or ""
            clickable = node.get("clickable", "false") == "true"
            enabled = node.get("enabled", "true") == "true"
            has_size = (x2 - x1) > 0 and (y2 - y1) > 0

            if not has_size:
                for child in node:
                    _extract(child, depth + 1)
                return

            # 只保留可点击或有文字/内容的元素
            has_content = bool(text or content_desc)
            is_interactive = clickable and enabled
            checkbox = node.get("checkable", "false") == "true"
            edit_field = type_short == "EditText"
            image_type = type_short == "ImageView"

            keep = (
                (is_interactive and has_size)
                or has_content
                or checkbox
                or edit_field
                or image_type
            )

            if keep:
                # YOLO 格式：归一化坐标
                cx = (x1 + x2) / 2 / image_width
                cy = (y1 + y2) / 2 / image_height
                w_val = (x2 - x1) / image_width
                h_val = (y2 - y1) / image_height
                cx = max(0.0, min(1.0, cx))
                cy = max(0.0, min(1.0, cy))
                w_val = max(0.001, min(1.0, w_val))
                h_val = max(0.001, min(1.0, h_val))

                # 获取或分配类别ID
                if type_short not in used_classes:
                    used_classes[type_short] = next_id
                    next_id += 1
                cls_id = used_classes[type_short]

                lines.append(f"{cls_id} {cx:.6f} {cy:.6f} {w_val:.6f} {h_val:.6f}")

                # 保存元数据（含文字内容），供后续OCR匹配和校验
                metadata.append({
                    "class_id": cls_id,
                    "type": type_short,
                    "text": text,
                    "content_desc": content_desc,
                    "resource_id": resource_id,
                    "x1": x1, "y1": y1, "x2": x2, "y2": y2,
                    "clickable": clickable,
                    "enabled": enabled,
                })

                # 统计类型频率
                type_scores[type_short] = type_scores.get(type_short, 0) + 1

            # 递归子节点（但跳过深层容器）
            if depth < 30:
                for child in node:
                    _extract(child, depth + 1)

        _extract(root)

        return "\n".join(lines), metadata

    def save_auto_labeled_sample(
        self,
        dataset_name: str,
        image_data: bytes,
        image_filename: str,
        dom_xml: str,
        image_width: int,
        image_height: int,
        split: str = "train",
    ) -> dict[str, Any]:
        """保存一张自动标注的训练样本（截图 + YOLO 标签 + 元数据）。

        Args:
            dataset_name: 数据集名称。
            image_data: PNG 截图的二进制数据。
            image_filename: 图片文件名（如 ``page_001.png``）。
            dom_xml: 对应的 uiautomator2 XML。
            image_width: 截图宽度（px）。
            image_height: 截图高度（px）。
            split: "train" 或 "val"。

        Returns:
            {"image_path": ..., "label_path": ..., "metadata_path": ...,
             "element_count": int, "element_types": [str, ...]}
        """
        ds_dir = self._root / dataset_name
        if not ds_dir.exists():
            raise FileNotFoundError(f"数据集 '{dataset_name}' 不存在")

        # 读取现有 classes 并构建 class_map
        class_map: dict[str, int] = {}
        classes_file = ds_dir / "classes.txt"
        if classes_file.exists():
            class_list = classes_file.read_text(encoding="utf-8").strip().split("\n")
            class_map = {name: i for i, name in enumerate(class_list) if name}

        # 生成标签 + 元数据
        label_text, metadata = self.auto_label_from_dom(
            dom_xml=dom_xml,
            image_width=image_width,
            image_height=image_height,
            class_map=class_map if class_map else None,
        )

        if not label_text.strip():
            return {"image_path": "", "label_path": "", "element_count": 0, "metadata_path": ""}

        # 文件名去掉扩展名
        stem = Path(image_filename).stem

        # 保存图片
        img_dir = ds_dir / "images" / split
        img_dir.mkdir(parents=True, exist_ok=True)
        img_path = img_dir / image_filename
        img_path.write_bytes(image_data)

        # 保存 YOLO 标签
        lbl_dir = ds_dir / "labels" / split
        lbl_dir.mkdir(parents=True, exist_ok=True)
        lbl_path = lbl_dir / f"{stem}.txt"
        lbl_path.write_text(label_text, encoding="utf-8")

        # 保存元数据 JSON（含每个元素的text/content_desc，供后续分析/校验）
        meta_dir = ds_dir / "metadata" / split
        meta_dir.mkdir(parents=True, exist_ok=True)
        meta_path = meta_dir / f"{stem}.json"
        import json
        meta_path.write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")

        # 更新 classes.txt 和 data.yaml
        element_types = sorted(set(m["type"] for m in metadata))
        if not classes_file.exists() or len(element_types) > len(class_map):
            classes_file.write_text("\n".join(element_types), encoding="utf-8")
        self._regenerate_data_yaml(ds_dir)

        return {
            "image_path": str(img_path),
            "label_path": str(lbl_path),
            "metadata_path": str(meta_path),
            "element_count": len(metadata),
            "element_types": element_types,
            "element_texts": [m.get("text", "") or m.get("content_desc", "") for m in metadata[:10]],
        }

    def _sync_classes_from_labels(
        self, ds_dir: Path, used_ids: set[int]
    ) -> None:
        """从已标注的标签文件中提取所有类别名称。"""
        all_types: set[str] = set()
        labels_dir = ds_dir / "labels"
        for split_dir in ["train", "val"]:
            lbl_dir = labels_dir / split_dir
            if not lbl_dir.exists():
                continue
            for f in sorted(lbl_dir.glob("*.txt")):
                for line in f.read_text(encoding="utf-8").strip().split("\n"):
                    if line.strip():
                        parts = line.strip().split()
                        if len(parts) >= 5:
                            cls_id = int(parts[0])
                            # 查找对应的类名（用默认名）
                            all_types.add(f"class_{cls_id}")

        # 按ID排序写入
        sorted_types = sorted(
            all_types,
            key=lambda x: int(x.split("_")[1]) if x.startswith("class_") else 999,
        )
        if sorted_types:
            ds_dir.joinpath("classes.txt").write_text(
                "\n".join(sorted_types), encoding="utf-8"
            )

    def _regenerate_data_yaml(self, ds_dir: Path) -> None:
        """重新生成 data.yaml（基于当前 classes.txt 和 images 目录）。"""
        classes: list[str] = []
        classes_file = ds_dir / "classes.txt"
        if classes_file.exists():
            classes = [
                c for c in classes_file.read_text(encoding="utf-8").strip().split("\n") if c
            ]
        self._generate_data_yaml(ds_dir, classes)
